export const normalizeSheetHotelName = (value: string) => value
  .replace(/[أإآ]/g, "ا")
  .replace(/ى/g, "ي")
  .replace(/ة/g, "ه")
  .replace(/\s+/g, " ")
  .trim()
  .replace("قرطبه", "قرطبة")
  .replace("نارسس", "نارسيس");

